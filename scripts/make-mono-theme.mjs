// Generates src/ui/theme-mono.css: a black-and-white theme layered on top of the existing stylesheets.
// Every green/teal colour found in the app stylesheets is overridden with a neutral grey of the same lightness
// (same selector, same @media context, loaded last), so the source stylesheets stay untouched and Codex's
// concurrent edits cannot conflict. Warning/danger/success hues are kept. Re-run after stylesheet changes:
//   node scripts/make-mono-theme.mjs
import fs from 'node:fs';
import postcss from 'postcss';

const SOURCES = ['src/styles.css', 'src/brief.css', 'src/components/workspace.css', 'src/components/design-guide.css', 'src/ui/ui.css'];
const OUT = 'src/ui/theme-mono.css';
const COLOR = /#([0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\b|rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+%?)\s*)?\)/gi;

function hexToRgba(hex) {
  let h = hex.slice(1);
  if (h.length <= 4) h = [...h].map(c => c + c).join('');
  return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)).concat(h.length === 8 ? [parseInt(h.slice(6, 8), 16) / 255] : [1]);
}
function hsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  if (!d) return [0, 0, l];
  const s = d / (1 - Math.abs(2 * l - 1));
  const h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [(h * 60 + 360) % 360, s, l];
}
/** Green, teal and cyan-ish brand colours become neutral; warm (warning/danger) and pure greys are kept. */
function isBrandHue(rgb) { const [h, s] = hsl(rgb); return s > .06 && h >= 70 && h <= 205; }
function neutral([r, g, b, a]) {
  const v = Math.round(hsl([r, g, b])[2] * 255);
  const hex = v.toString(16).padStart(2, '0');
  return a >= 1 ? `#${hex}${hex}${hex}` : `rgba(${v},${v},${v},${+a.toFixed(3)})`;
}
/** Text on the white theme must stay readable (WCAG AA ~4.5:1): mid-grey text is darkened to #666 or darker. */
function readableText([r, g, b, a]) {
  const l = hsl([r, g, b])[2];
  return l > .42 && l < .9 && a > .5 ? [102, 102, 102, a] : null;
}
function convert(value, prop = '') {
  let changed = false;
  const next = value.replace(COLOR, (m, hex, r, g, b, a) => {
    const rgba = hex ? hexToRgba(m) : [+r, +g, +b, a === undefined ? 1 : a.endsWith('%') ? parseFloat(a) / 100 : +a];
    const text = prop === 'color' ? readableText(rgba) : null;
    if (text) { changed = true; return neutral(text); }
    if (!isBrandHue(rgba)) return m;
    changed = true;
    return neutral(rgba);
  });
  return changed ? next : null;
}

const out = postcss.root();
let overrides = 0;
for (const file of SOURCES) {
  if (!fs.existsSync(file)) continue;
  const root = postcss.parse(fs.readFileSync(file, 'utf8'), {from: file});
  root.walkRules(rule => {
    if (rule.parent?.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
    const decls = [];
    rule.each(node => {
      if (node.type !== 'decl' || node.prop.startsWith('--')) return;
      const value = convert(node.value, node.prop);
      if (value) decls.push(postcss.decl({prop: node.prop, value, important: node.important}));
    });
    if (!decls.length) return;
    overrides += decls.length;
    let target = out;
    const chain = [];
    for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) chain.unshift(p);
    for (const at of chain) {
      let found = target.nodes.find(n => n.type === 'atrule' && n.name === at.name && n.params === at.params);
      if (!found) { found = postcss.atRule({name: at.name, params: at.params}); target.append(found); }
      target = found;
    }
    target.append(postcss.rule({selector: rule.selector, nodes: decls}));
  });
}

